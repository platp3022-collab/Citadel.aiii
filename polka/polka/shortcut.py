"""Рецепт команды быстрого доступа: python3 -m polka.shortcut

Печатает готовые значения для двойного касания задней крышки айфона.
Собирать команду в «Быстрых командах» всё равно придётся руками: Apple не
даёт создать её из файла без подписи в iCloud.
"""
from __future__ import annotations

import sys

from .config import load_config

RECIPE = """
════════════════════════════════════════════════════════════════════
  ДВОЙНОЕ КАСАНИЕ ЗАДНЕЙ КРЫШКИ
════════════════════════════════════════════════════════════════════

Адрес ниже постоянный: собрать команду надо один раз, и она будет
работать всегда, даже когда Полка перезапускается.

Открой на айфоне «Быстрые команды», плюс в углу, и собери команду
из двух действий.

── Действие 1: Диктовка текста ─────────────────────────────────────

  Найди в поиске «Диктовка текста» и добавь.
  Нажми «Показать больше» и поставь:

    Язык:      Русский
    Остановка: После паузы

── Действие 2: Получить содержимое URL ─────────────────────────────

  Найди «Получить содержимое URL» и добавь следующим.

    URL:    {relay}

  Нажми «Показать больше»:

    Метод:  POST

    Тело запроса:  Файл
      В поле значения вставь переменную «Продиктованный текст»
      (она появится над клавиатурой)

── Имя и запуск ────────────────────────────────────────────────────

  Назови команду «Полка» и сохрани.

  Настройки → Универсальный доступ → Касание → Касание задней панели
  → Двойное касание → выбери «Полка».

════════════════════════════════════════════════════════════════════

Как это работает: у Полки дома нет своего адреса в интернете, поэтому
она сама держит связь с доской объявлений, а телефон кладёт туда текст.
Имя доски и есть пароль, никому его не показывай.

Теперь двойное касание начинает запись. Говори как есть, со всеми «ээ»
и «короче»: разбор вычистит мусор, поймает самоисправления и положит
мысль на нужную полку. Карточка с вопросом придёт в Telegram.

Проверить прямо сейчас, не вставая:

  curl -d "проверка двойного касания" {relay}

Через пару секунд бот должен прислать карточку.
"""

NO_RELAY = """
Канал для двойного касания ещё не заведён.

Запусти мастер, он сделает это сам:

  python3 -m polka.wizard
"""


def main() -> int:
    cfg = load_config()
    if not cfg.relay_topic:
        print(NO_RELAY, file=sys.stderr)
        return 1
    print(RECIPE.format(relay=f"{cfg.relay_url}/{cfg.relay_topic}"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
