"""Рецепт команды быстрого доступа: python3 -m polka.shortcut

Печатает готовые значения для двойного касания задней крышки айфона.
Собирать команду в приложении «Быстрые команды» всё равно придётся руками:
Apple не даёт создать её из файла без подписи в iCloud.
"""
from __future__ import annotations

import sys

from .config import load_config

RECIPE = """
════════════════════════════════════════════════════════════════════
  ДВОЙНОЕ КАСАНИЕ ЗАДНЕЙ КРЫШКИ
════════════════════════════════════════════════════════════════════

Открой на айфоне приложение «Быстрые команды», плюс в углу, и собери
команду из двух действий.

── Действие 1: Диктовка текста ─────────────────────────────────────

  Найди в поиске «Диктовка текста» и добавь.
  Нажми на слово «Показать больше» и поставь:

    Язык:      Русский
    Остановка: После паузы

── Действие 2: Получить содержимое URL ─────────────────────────────

  Найди «Получить содержимое URL» и добавь следующим.

    URL:    {url}/api/capture

  Нажми «Показать больше» и заполни:

    Метод:  POST

    Заголовки, нажми плюс:
      Ключ:      X-Polka-Token
      Значение:  {token}

    Тело запроса:  JSON
      Нажми плюс, выбери «Текст»
      Ключ:      text
      Значение:  вставь переменную «Продиктованный текст»
                 (она появится над клавиатурой)

── Имя и запуск ────────────────────────────────────────────────────

  Назови команду «Полка» и сохрани.

  Настройки → Универсальный доступ → Касание → Касание задней панели
  → Двойное касание → выбери «Полка».

════════════════════════════════════════════════════════════════════

Теперь двойное касание по крышке начинает запись. Говори как есть, со
всеми «ээ» и «короче»: разбор вычистит мусор, поймает самоисправления
и положит мысль на нужную полку. Карточка придёт в Telegram.

Проверить, что адрес отвечает, можно прямо с компьютера:

  curl -X POST {url}/api/capture \\
       -H "X-Polka-Token: {token}" \\
       -H "Content-Type: application/json" \\
       -d '{{"text": "проверка команды"}}'
"""

NO_URL = """
Пока нет публичного адреса, команде некуда отправлять мысль.

Адрес появляется, когда поднят туннель или Полка стоит на сервере:

  python3 -m polka.setup --tunnel          временный адрес
  python3 -m polka.setup --url https://…   свой домен

Важно: временный адрес меняется при каждом запуске, и команду придётся
править каждый раз. Для двойного касания нужен постоянный адрес, то есть
сервер со своим доменом.
"""


def main() -> int:
    cfg = load_config()
    if not cfg.public_url:
        print(NO_URL)
        return 1
    if not cfg.capture_token:
        print("\nВ polka/.env нет POLKA_CAPTURE_TOKEN. Запусти python3 -m polka.wizard,"
              "\nон заведёт ключ сам.\n", file=sys.stderr)
        return 1
    print(RECIPE.format(url=cfg.public_url, token=cfg.capture_token))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
